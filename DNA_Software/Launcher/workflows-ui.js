"use strict";
window.renderWorkflowsPage = async function () {
  const pid = currentPerson(),
    epoch = renderEpoch;
  header(
    "Workflows",
    "Workflows",
    t("Prepare once, reuse results and complete only missing steps.")
  );
  if (!pid) {
    $("main").append(empty(t("Select a profile.")));
    return;
  }
  const data = await profileCommand("workflows.list", { person: pid });
  if (epoch !== renderEpoch) return;
  const grid = el("div", "", "task-grid");
  for (const recipe of data.recipes) {
    const c = el("section", "", "card workflow-recipe");
    c.append(
      el("span", recipe.icon, "workflow-symbol"),
      el("h2", t(recipe.title_de, recipe.title)),
      el("p", recipe.steps.join(" → "), "field-help"),
      button(t("Plan workflow"), () => show(recipe), "primary")
    );
    grid.append(c);
  }
  $("main").append(grid);
  const detail = el("section", "", "card");
  $("main").append(detail);
  const labels = {
    ready: ["Bereit", "Ready"],
    reusable: ["✓ Already available", "✓ Saved result"],
    reused: ["✓ Wiederverwendet", "✓ Reused"],
    completed: ["✓ Completed", "✓ Complete"],
    running: ["Running", "Running"],
    needs_input: ["Eingaben fehlen", "Inputs needed"],
    needs_attention: ["Testing required", "Needs attention"],
    blocked: ["Predecessors are missing", "Predecessor needed"],
  };
  function label(s) {
    return labels[s] ? t(...labels[s]) : s;
  }
  async function configure(step, recipe) {
    if (step.task === "profile_analyze") {
      go("intake");
      return;
    }
    await openTask(step.task, pid);
    for (const [key, value] of Object.entries(step.inputs || {})) {
      const node = fieldNodes[key];
      if (!node) continue;
      node.value = Array.isArray(value) ? value.join(" | ") : value;
      if (Array.isArray(value)) node.dataset.paths = JSON.stringify(value);
    }
    if (refreshTaskResult) await refreshTaskResult();
    document.getElementById("save-workflow-inputs")?.remove();
    const save = button(
      t("Use for workflow"),
      async () => {
        await profileCommand("workflows.configure", {
          person: pid,
          task: step.task,
          inputs: inputs(),
          recipe: recipe.id,
        });
        $("task-dialog").close();
        save.remove();
        await show(recipe);
      },
      "primary"
    );
    save.id = "save-workflow-inputs";
    $("task-dialog").querySelector(".dialog-actions").prepend(save);
  }
  async function show(recipe) {
    const p = await profileCommand("workflows.plan", { person: pid, recipe: recipe.id });
    if (epoch !== renderEpoch) return;
    detail.replaceChildren(
      el("span", "SHARED EVIDENCE", "eyebrow"),
      el("h2", t(recipe.title_de, recipe.title)),
      el(
        "p",
        t(
          "Each start is explicit. Missing references/tools pause the affected step. Fitness/nutrition require deliberately selected, relevant scores. This is not clinical validation."
        )
      )
    );
    drawSteps(p.steps, recipe);
    const actions = el("div", "", "actions");
    actions.append(
      button(
        t("Run available steps"),
        async () => {
          const job = await profileCommand("workflows.start", { person: pid, recipe: recipe.id });
          await poll(job, recipe);
        },
        "primary"
      )
    );
    detail.append(actions);
    detail.scrollIntoView({ block: "start", behavior: "smooth" });
  }
  function drawSteps(steps, recipe) {
    const chain = el("div", "", "workflow-chain");
    for (const [index, s] of steps.entries()) {
      const c = el("article", "", "workflow-step");
      c.dataset.state = s.status;
      c.append(
        el("span", String(index + 1).padStart(2, "0"), "workflow-number"),
        el(
          "h3",
          s.task === "parent_origin"
            ? t("Check parental transmission")
            : title(
                state.catalog.tasks.find((x) => x.id === s.task) || { title: s.title, id: s.task }
              )
        ),
        el("span", label(s.status), "pill"),
        el("p", s.tools, "field-help")
      );
      if (s.inputs?.target)
        c.append(
          el(
            "p",
            t("Comparison: ") +
              t(
                s.inputs.target,
                s.inputs.target === "Getrennt belassen" ? "Keep builds separate" : s.inputs.target
              ),
            "field-help"
          )
        );
      if (s.missing?.length) c.append(el("p", t("Missing: ") + s.missing.join(", "), "warning"));
      if (s.error) c.append(el("p", s.error, "field-help"));
      if (s.job) c.append(el("p", t("Generated by: ") + s.task + " / " + s.job, "field-help"));
      if (s.autofill?.length)
        c.append(
          el("p", s.autofill.map((x) => x.field + " ← " + x.origin).join("; "), "field-help")
        );
      if (s.task !== "parent_origin")
        c.append(button(t("Inputs / open tool"), () => configure(s, recipe), "secondary"));
      chain.append(c);
    }
    detail.append(chain);
  }

  async function poll(job, recipe) {
    const r = await profileCommand("workflows.status", job);
    if (epoch !== renderEpoch || pid !== currentPerson()) return;
    detail.replaceChildren(el("h2", t(recipe.title_de, recipe.title)));
    const meter = el("progress");
    meter.max = 100;
    meter.value = r.percent;
    meter.setAttribute("aria-label", t("Workflow progress"));
    detail.append(
      el("p", r.completed + " / " + r.total + " · " + r.percent + "% · " + label(r.state)),
      meter
    );
    drawSteps(r.steps, recipe);
    const log = el("pre", r.log.join("\n") || t("Preparing job …"), "workflow-console");
    log.setAttribute("role", "log");
    log.setAttribute("aria-live", "polite");
    detail.append(log);
    if (r.state === "running") {
      detail.append(
        button(t("Request cancellation"), () => profileCommand("workflows.cancel", job), "danger")
      );
      setTimeout(() => run(() => poll(job, recipe)), 1800);
    } else
      detail.append(
        button(t("Review plan / continue"), () => show(recipe), "primary"),
        button(t("Manage outputs"), () => go("file-manager"), "secondary")
      );
  }
  const past = el("section", "", "card");
  past.append(el("h2", t("Saved workflows")));
  for (const r of data.runs) {
    const recipe = data.recipes.find((x) => x.id === r.recipe);
    if (!recipe) continue;
    past.append(
      button(
        t(recipe.title_de, recipe.title) +
          " · " +
          r.created +
          " · " +
          r.percent +
          "% · " +
          label(r.state),
        () => poll({ person: pid, job: r.job }, recipe),
        "secondary"
      )
    );
  }
  $("main").append(past);
  if (data.runs[0]?.state === "running") {
    const r = data.runs[0],
      recipe = data.recipes.find((x) => x.id === r.recipe);
    if (recipe) await poll({ person: pid, job: r.job }, recipe);
  }
};
window.appendInheritanceCard = async function (container, pid) {
  const r = await profileCommand("inheritance.read", { person: pid });
  if (!r || pid !== currentPerson()) return;
  const c = el("section", "", "card");
  c.append(
    el("h2", t("Parental lineages & transmission")),
    el("p", r.summary),
    el(
      "p",
      t("Data snapshot: ") +
        r.created +
        " · " +
        (r.current ? t("Current") : t("Changed — review again"))
    ),
    el("p", t("Maternal lineage: ") + r.maternal_line.join(" ← ")),
    el("p", t("Paternal lineage: ") + r.paternal_line.join(" ← ")),
    notice(
      t(
        "Lineages are documented family relationships. Assigned alleles are a bounded, quality-filtered trio subset, not full phasing. Parent DNA is never presented as a measured child genotype."
      )
    ),
    button(t("Open family workflow"), () => go("workflows"))
  );
  container.append(c);
};
